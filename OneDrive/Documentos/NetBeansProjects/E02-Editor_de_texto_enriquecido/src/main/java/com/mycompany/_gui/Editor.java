    //Clase para Abir un archivo
    public void abrirArhivoRTF(JTextPane textPane) {
        JFileChooser fileChooser = new JFileChooser();
        
        //Filtro para los archuvos RTF
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("Archivos RTF (*.rtf)", "rtf");
        fileChooser.setFileFilter(filtro);
        
        int seleccion = fileChooser.showOpenDialog(null);
        if (seleccion == JFileChooser.APPROVE_OPTION) {
            try (FileInputStream fis = new FileInputStream(fileChooser.getSelectedFile())) {
                RTFEditorKit rtfKit = (RTFEditorKit) JTextPane.getEditorKit();
                
                // Limpia el contenido actual y carga el nuevo documento RTF
                textPane.setText("");
                rtfKit.read(fis, textPane.getDocument(), 0);
            } catch (Exception ex) {
                ex.printStackTrace(); // O mostrar un JOptionPane con el error
            }
        } 
    }
    
    public void guardarComoRTF(JTextPane textPane) {
    JFileChooser fileChooser = new JFileChooser();
    FileNameExtensionFilter filtro = new FileNameExtensionFilter("Archivos RTF (*.rtf)", "rtf");
    fileChooser.setFileFilter(filtro);

    int seleccion = fileChooser.showSaveDialog(null);
    if (seleccion == JFileChooser.APPROVE_OPTION) {
        File archivo = fileChooser.getSelectedFile();
        
        // Asegurar que tenga la extensión .rtf
        if (!archivo.getName().toLowerCase().endsWith(".rtf")) {
            archivo = new File(archivo.getAbsolutePath() + ".rtf");
        }

        try (FileOutputStream fos = new FileOutputStream(archivo)) {
            RTFEditorKit rtfKit = (RTFEditorKit) textPane.getEditorKit();
            
            // Escribir el documento completo con formato en el archivo
            rtfKit.write(fos, textPane.getDocument(), 0, textPane.getDocument().getLength());
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }
}
// Método para cambiar el tamaño según el valor del spinner
private void aplicarTamanoFuente() {
    // 1. Lectura segura del valor numérico
    if (spinTamanoFuente.getValue() == null) return;
    int nuevoTamaño = ((Number) spinTamanoFuente.getValue()).intValue();

    // 2. Obtener la selección actual
    int inicio = JTextPane.getSelectionStart();
    int fin = JTextPane.getSelectionEnd();
    int longitud = fin - inicio;

    SimpleAttributeSet attrs = new SimpleAttributeSet();
    StyleConstants.setFontSize(attrs, nuevoTamaño);

    // 3. Aplicar al texto seleccionado o al cursor de entrada
    if (longitud > 0) {
        JTextPane.getStyledDocument().setCharacterAttributes(inicio, longitud, attrs, false);
    } else {
        // Opción 1: Aplica el estilo en la posición del cursor de entrada
        JTextPane.setCharacterAttributes(attrs, false);
    }
}

