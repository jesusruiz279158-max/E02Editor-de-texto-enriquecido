    // Clase para alternar el texto en Negrita
    public void alternarNegrita (JTextPane textPane) {
        //1. Obtener el rango de seleccion
        int inicio = JTextPane.getSelectionStart();
        int fin = JTextPane.getSelectionEnd();
        
        //2. Obtener los atributos de la seleccion
        AttributeSet attrs = textPane.getCharacterAttributes();
        boolean esNegrita = StyleConstants.isBold(attrs);
        
        //3. Crear el conjunto para aplicar el cambio
        SimpleAttributeSet nuevosAtributos = new SimpleAttributeSet();
        StyleConstants.setBold(nuevosAtributos, !esNegrita); //Invierte el texto de Negrita a normal
        
        //4. Aplicar el cambio al texto
        textPane.getStyledDocument().setCharacterAttributes(inicio, fin - inicio, nuevosAtributos, false);
    }
    
